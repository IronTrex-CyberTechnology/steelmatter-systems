// smschemas generates the SDK's dependency-free response schema snapshot.
// Run from the repository root: go run ./cmd/smschemas
package main

import (
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"go.yaml.in/yaml/v3"
)

type object = map[string]any

func obj(v any) object { return v.(map[string]any) }
func must(err error) {
	if err != nil {
		panic(err)
	}
}
func main() {
	data, err := os.ReadFile("api/openapi.yaml")
	must(err)
	var spec object
	must(yaml.Unmarshal(data, &spec))
	schemas := obj(obj(spec["components"])["schemas"])
	hashes := map[string]string{"api/openapi.yaml": fmt.Sprintf("%x", sha256.Sum256(data))}
	paths, err := filepath.Glob("schemas/*.schema.json")
	must(err)
	for _, p := range paths {
		b, e := os.ReadFile(p)
		must(e)
		var s object
		must(json.Unmarshal(b, &s))
		schemas["../"+filepath.ToSlash(p)] = s
		hashes[filepath.ToSlash(p)] = fmt.Sprintf("%x", sha256.Sum256(b))
	}
	used := object{}
	allowed := strings.Fields("$ref type const enum properties required additionalProperties items minItems maxItems uniqueItems minLength maxLength pattern format minimum maximum oneOf allOf")
	var clean func(object) object
	clean = func(s object) object {
		out := object{}
		for k, v := range s {
			if k == "description" || k == "title" || k == "$schema" || k == "$id" {
				continue
			}
			known := false
			for _, a := range allowed {
				if k == a {
					known = true
				}
			}
			if !known {
				panic("unsupported schema keyword: " + k)
			}
			out[k] = v
		}
		if v, ok := out["$ref"].(string); ok {
			ref := strings.TrimPrefix(v, "#/components/schemas/")
			out["$ref"] = ref
			if _, exists := used[ref]; !exists {
				used[ref] = nil
				used[ref] = clean(obj(schemas[ref]))
			}
		}
		if v, ok := out["properties"]; ok {
			props := object{}
			for k, s := range obj(v) {
				props[k] = clean(obj(s))
			}
			out["properties"] = props
		}
		if v, ok := out["items"]; ok {
			out["items"] = clean(obj(v))
		}
		for _, k := range []string{"oneOf", "allOf"} {
			if v, ok := out[k]; ok {
				list := []any{}
				for _, item := range v.([]any) {
					list = append(list, clean(obj(item)))
				}
				out[k] = list
			}
		}
		// The runtime implements only the subset used by the R0 response
		// contract. Refuse future schema features rather than silently weakening
		// validation when the snapshot is regenerated.
		if t, ok := out["type"]; ok {
			switch t {
			case "object", "array", "string", "integer", "boolean":
			default:
				panic(fmt.Sprintf("unsupported schema type: %v", t))
			}
		}
		if f, ok := out["format"]; ok && f != "date-time" {
			panic(fmt.Sprintf("unsupported schema format: %v", f))
		}
		if p, ok := out["additionalProperties"]; ok {
			if _, boolean := p.(bool); !boolean {
				panic("additionalProperties must be boolean")
			}
		}
		if out["uniqueItems"] == true {
			item := obj(out["items"])
			for item["$ref"] != nil {
				item = obj(used[item["$ref"].(string)])
			}
			switch item["type"] {
			case "string", "integer", "boolean":
			default:
				panic("uniqueItems requires scalar items")
			}
		}
		return out
	}
	responses := object{}
	for _, path := range obj(spec["paths"]) {
		for _, raw := range obj(path) {
			op := obj(raw)
			statuses := object{}
			for status, r := range obj(op["responses"]) {
				if strings.HasPrefix(status, "2") {
					statuses[status] = clean(obj(obj(obj(obj(r)["content"])["application/json"])["schema"]))
				}
			}
			responses[op["operationId"].(string)] = statuses
		}
	}
	clean(object{"$ref": "#/components/schemas/Error"})
	output := "// Generated by go run ./cmd/smschemas; do not edit by hand.\nimport type { Schema } from './response-validation.ts';\n"
	for _, entry := range []struct {
		name  string
		value any
	}{
		{"schemaSources", hashes}, {"responseSchemas: Record<string, Schema>", used}, {"operationResponses: Record<string, Record<string, Schema>>", responses},
	} {
		b, e := json.MarshalIndent(entry.value, "", "  ")
		must(e)
		output += "export const " + entry.name + " = " + string(b) + ";\n"
	}
	must(os.WriteFile("packages/sdk/src/response-schemas.ts", []byte(output), 0644))
}
