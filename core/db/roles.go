// Package db owns PostgreSQL bootstrap, roles and schema migrations.
//
// Privilege model (document 02, invariants I7 and I9):
//   - GroupExecutor: the service's write role. It receives explicit per-table
//     grants in migrations and never owns objects, so it cannot run DDL.
//   - GroupObserver: read-only. It receives SELECT on the target projection only.
//   - Actors have no database credentials at all; they reach the service over HTTP.
//
// Group roles are NOLOGIN and cluster-wide. Login roles are created per
// database and inherit from a group, so disposable test databases on a shared
// cluster never share credentials.
package db

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

const (
	GroupExecutor = "steelmatter_executor"
	GroupObserver = "steelmatter_observer"
)

// Querier is the subset of pgx used by bootstrap code; satisfied by *pgx.Conn,
// *pgxpool.Pool and pgx.Tx.
type Querier interface {
	Exec(ctx context.Context, sql string, args ...any) (pgconn.CommandTag, error)
	QueryRow(ctx context.Context, sql string, args ...any) pgx.Row
}

// EnsureGroupRoles creates the NOLOGIN group roles if they are absent.
// Concurrent creators on the same cluster are tolerated.
func EnsureGroupRoles(ctx context.Context, q Querier) error {
	for _, role := range []string{GroupExecutor, GroupObserver} {
		var exists bool
		if err := q.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = $1)`, role).Scan(&exists); err != nil {
			return fmt.Errorf("check role %s: %w", role, err)
		}
		if exists {
			continue
		}
		_, err := q.Exec(ctx, "CREATE ROLE "+ident(role)+" NOLOGIN NOINHERIT")
		if err != nil && !isDuplicate(err) {
			return fmt.Errorf("create role %s: %w", role, err)
		}
	}
	return nil
}

// CreateLoginRole creates a LOGIN role that inherits the privileges of group.
// The password must come from RandomPassword (hex only), which keeps the
// literal safe because PostgreSQL does not accept bind parameters here.
func CreateLoginRole(ctx context.Context, q Querier, name, password, group string) error {
	if !isHex(password) {
		return errors.New("login role password must be hex generated by RandomPassword")
	}
	sql := fmt.Sprintf("CREATE ROLE %s LOGIN INHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '%s' IN ROLE %s",
		ident(name), password, ident(group))
	if _, err := q.Exec(ctx, sql); err != nil {
		return fmt.Errorf("create login role %s: %w", name, err)
	}
	return nil
}

// RandomPassword returns 32 random bytes as lowercase hex.
func RandomPassword() (string, error) {
	b := make([]byte, 32)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return hex.EncodeToString(b), nil
}

func ident(name string) string { return pgx.Identifier{name}.Sanitize() }

func isDuplicate(err error) bool {
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) {
		return false
	}
	// 42710 duplicate_object; 23505 unique_violation (pg_authid race).
	return pgErr.Code == "42710" || pgErr.Code == "23505"
}

func isHex(s string) bool {
	if s == "" {
		return false
	}
	for _, c := range s {
		if !(c >= '0' && c <= '9' || c >= 'a' && c <= 'f') {
			return false
		}
	}
	return true
}
